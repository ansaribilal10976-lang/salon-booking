import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const sources = [
  "20261005000000_create_services_and_bookings.sql",
  "20261005010000_add_guest_booking_rpcs.sql",
  "20261005020000_add_admin_dashboard.sql",
  "20261005030000_allow_public_booking_inserts.sql",
];
const destination = new URL("supabase/salon_booking_schema.sql", root);
const sections = [];
for (const name of sources) {
  const source = await readFile(new URL(`supabase/migrations/${name}`, root), "utf8");
  const wrapped = source.match(/^begin;\r?\n([\s\S]*?)\r?\ncommit;\s*$/);
  if (!wrapped) throw new Error(`Unexpected transaction wrapper in ${name}`);
  sections.push(`-- Source: supabase/migrations/${name}\n${wrapped[1].trim()}`);
}

const header = `-- SALON BOOKING: TABLES, RLS, VALIDATION, AND APPLICATION RPCS
-- Generated by: node scripts/export-supabase-schema.mjs
-- FRESH SUPABASE PROJECT ONLY. Run once as the owner in the SQL Editor.
-- Do NOT run alongside the numbered migrations or over an existing salon schema.
-- For existing projects, apply only unapplied files from supabase/migrations/.
-- Supabase must already provide auth.users, auth.uid(), anon, authenticated.
-- No credentials, admin accounts, or sample customer/service data are seeded.
-- The salon timezone defaults to UTC; configure the real zone before launch.
-- After setup, provision a Supabase Auth user and add its UUID to
-- private.salon_admins as the owner. See README.md for configuration and tests.
-- SQL runtime validation has not been performed in the Android workspace.

begin;

do $preflight$
begin
  if pg_catalog.to_regclass('public.services') is not null
     or pg_catalog.to_regclass('public.bookings') is not null
     or pg_catalog.to_regtype('public.booking_status') is not null
     or pg_catalog.to_regclass('private.salon_booking_settings') is not null
     or pg_catalog.to_regclass('private.salon_admins') is not null then
    raise exception using errcode = '42P07',
      message = 'Salon objects already exist. Use only unapplied numbered migrations, not the fresh-project SQL bundle.';
  end if;
end;
$preflight$;
`;
const bundle = `${header}\n${sections.join("\n\n")}\n\ncommit;\n`;

if (process.argv.includes("--check")) {
  if (await readFile(destination, "utf8") !== bundle) {
    throw new Error("SQL bundle differs from its migration sources. Regenerate it.");
  }
  console.log("SQL bundle exactly matches all four migration bodies and its fresh-project guard. This is not a PostgreSQL execution test.");
} else {
  await writeFile(destination, bundle, { flag: "w" });
  console.log("Wrote supabase/salon_booking_schema.sql from all four migrations.");
}
